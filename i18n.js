// Memo for trLimit, keyed on (language, raw). The rules are a pure rewrite and
// there are now 646 of them: the comparison grid alone is ~14,000 cells, so a
// full re-render was running about 9 million regex passes — over a second of
// pure regex on every filter keystroke. The keys come from the shipped database,
// so the map is bounded by the few thousand distinct limit strings in it.
const LIMIT_MEMO = new Map();

// Translate an English limit cell into the current language, preserving the
// numbers and footnote markers exactly as printed.
function trLimit(raw) {
  if (LANG === 'en' || !raw) return raw;
  const key = LANG + '\u0000' + raw;
  const memo = LIMIT_MEMO.get(key);
  if (memo !== undefined) return memo;
  const idx = LANG === 'hk' ? 1 : 2;
  let out = String(raw);
  for (const rule of LIMIT_RULES) out = out.replace(rule[0], rule[idx]);
  for (const [re, rep] of REORDER) out = out.replace(re, rep);
  out = out.replace(/,\s+(?=\D)/g, '，').replace(/\s{2,}/g, ' ').trim();
  LIMIT_MEMO.set(key, out);
  return out;
}
